--Time Travel Recovery
CREATE OR REPLACE TABLE FACT_SALES_RECOVERY
AS
SELECT *
FROM FACT_SALES
AT (OFFSET => -60*5);

--Zero Copy Cloning
CREATE OR REPLACE SCHEMA RETAIL_MART_RECOVERY
CLONE RETAIL_MART;

--Masking Policy
CREATE OR REPLACE MASKING POLICY EMAIL_MASK_POLICY
AS (VAL STRING)
RETURNS STRING ->
CASE
    WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN','SYSADMIN')
    THEN VAL
    WHEN CURRENT_ROLE() = 'DATA_ANALYST'
    THEN CONCAT('XXXXXX', RIGHT(VAL, 8))
    ELSE '********'
END;