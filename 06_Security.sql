GRANT USAGE ON DATABASE RETAIL_DB TO ROLE BUSINESS_MANAGER;
GRANT USAGE ON SCHEMA RETAIL_MART TO ROLE BUSINESS_MANAGER;

GRANT SELECT ON TABLE RETAIL_MART.DIM_CUSTOMER TO ROLE DATA_ANALYST;
GRANT SELECT ON TABLE RETAIL_MART.DIM_PRODUCT TO ROLE DATA_ANALYST;
GRANT SELECT ON TABLE RETAIL_MART.DIM_BRANCH TO ROLE DATA_ANALYST;
GRANT SELECT ON TABLE RETAIL_MART.DIM_DATE TO ROLE DATA_ANALYST;
GRANT SELECT ON TABLE RETAIL_MART.FACT_SALES TO ROLE DATA_ANALYST;

GRANT SELECT ON TABLE RETAIL_MART.DIM_CUSTOMER TO ROLE BUSINESS_MANAGER;
GRANT SELECT ON TABLE RETAIL_MART.DIM_PRODUCT TO ROLE BUSINESS_MANAGER;
GRANT SELECT ON TABLE RETAIL_MART.DIM_BRANCH TO ROLE BUSINESS_MANAGER;
GRANT SELECT ON TABLE RETAIL_MART.DIM_DATE TO ROLE BUSINESS_MANAGER;
