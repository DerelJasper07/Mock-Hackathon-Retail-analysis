SELECT * FROM RAW_FRAUD_SALES_ALERT;


--Dynamic table to flatten json data
CREATE OR REPLACE DYNAMIC TABLE FLAT_FRAUD_SALES_ALERT
TARGET_LAG = '1 MINUTE'
WAREHOUSE = RETAIL_WH
AS
SELECT
    VALUE:ID::STRING AS ID,
    VALUE:TRANSACTION_ID::STRING AS TRANSACTION_ID,
    VALUE:REASON::STRING AS REASON,
    VALUE:FRAUD_SCORE::NUMBER AS FRAUD_SCORE,
    VALUE:STATUS::STRING AS STATUS
FROM RAW_FRAUD_SALES_ALERT,
LATERAL FLATTEN(INPUT => RAW_DATA);

SELECT * FROM FLAT_FRAUD_SALES_ALERT;